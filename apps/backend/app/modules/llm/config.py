def build_asuna_system_message(mode: str = "default"):
    """生成人设系统提示词"""
    if mode not in MODE_INSTRUCTIONS:
        mode = "default"

    return SystemMessage(content=ASUNA_CORE + "\n\n" + MODE_INSTRUCTIONS[mode])


