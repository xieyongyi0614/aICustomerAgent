def kebab(dart_name: str) -> str:
    out = []
    for c in dart_name:
        out.append(f"-{c.lower()}" if c.isupper() else c)
    return "".join(out).lstrip("-")


def main() -> None:
    # getBestCmap 返回 {码点: 字形名}，反转成 {字形名: 码点} 供语义名查询
    name_to_cp = {
        name: cp for cp, name in TTFont(str(FONT)).getBestCmap().items()
    }
    lines = [
        "// GENERATED by tool/gen_app_icons.py — 勿手改码点；新增图标在脚本 ICONS 表登记后重新生成。",
        "// codepoint 以 fonts/lucide.ttf 的 cmap 为唯一真源；test/design_system/app_icons_font_test.dart 会校验。",
        "// 自建 IconData 兼容 Flutter 3.47+ final IconData；lucide_icons 包本体在该版本编译不过，勿引回。",
        "import 'package:flutter/material.dart';",
        "",
        "/// Lucide 线性图标（字体 family = lucide；语义名即 API，码点无需人工读写）。",
        "class AppIcons {",
        "  const AppIcons._();",
        "",
    ]
    seen = set()
    for dart, glyph in ICONS:
        if glyph not in name_to_cp:
            raise SystemExit(
                f"字形缺失：{glyph}（dart: {dart}）不在 {FONT.name} 的 cmap 中"
            )
        cp = name_to_cp[glyph]
        if cp in seen:
            raise SystemExit(f"码点冲突：{glyph} 与已有图标共用 0x{cp:04x}")
        seen.add(cp)
        suffix = f"  // lucide: {glyph}" if kebab(dart) != glyph else ""
        lines.append(
            f"  static const {dart} = IconData(0x{cp:04x},"
            f" fontFamily: 'lucide');{suffix}"
        )
    lines.append("}")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"generated {TARGET} with {len(ICONS)} icons")


if __name__ == "__main__":
    main()
